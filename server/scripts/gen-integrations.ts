/**
 * V2 (T8/T10) — generate the frontend mirror of the integration-status config.
 *
 * Run after editing server/src/config/integration-status.ts:
 *   cd server && npx tsx scripts/gen-integrations.ts
 */
import { writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { buildIntegrationsPayload } from "../src/config/integration-status";

const payload = buildIntegrationsPayload();
const version = Buffer.from(JSON.stringify(payload)).toString("base64").slice(0, 12);
const target = path.resolve(__dirname, "../../frontend/src/lib/integrations.autogen.ts");

const body = `// AUTO-GENERATED by server/scripts/gen-integrations.ts — DO NOT EDIT BY HAND.
// Source of truth: server/src/config/integration-status.ts
// Regenerate: cd server && npx tsx scripts/gen-integrations.ts
// Content hash: INTEGRATIONS_VERSION

export const INTEGRATIONS_VERSION = "${version}";

export const INTEGRATIONS = ${JSON.stringify(payload, null, 2)} as const;
`;

mkdirSync(path.dirname(target), { recursive: true });
writeFileSync(target, body, "utf8");
console.log(`Wrote ${path.relative(process.cwd(), target)} (version ${version})`);
