/**
 * gen-plans — emits frontend/src/lib/plans.autogen.ts from the CANONICAL
 * plans config (src/config/plans.ts). Run from the server/ directory:
 *
 *   npx tsx scripts/gen-plans.ts
 *
 * The emitted file carries a short content hash (PLANS_VERSION). The unit
 * test plans-config.test.ts recomputes the hash server-side and fails if the
 * emitted file has drifted from the canonical config.
 *
 * NEVER hand-edit the emitted file — change the config and re-run this.
 */
import { writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { buildPlansPayload } from "../src/config/plans";

const payload = buildPlansPayload();
const json = JSON.stringify(payload, null, 2);
const version = createHash("sha256").update(json).digest("hex").slice(0, 12);

const outPath = "../frontend/src/lib/plans.autogen.ts";

const file = `// AUTO-GENERATED by server/scripts/gen-plans.ts — DO NOT EDIT BY HAND.
// Source of truth: server/src/config/plans.ts. Regenerate with:
//   cd server && npx tsx scripts/gen-plans.ts
// Content hash: PLANS_VERSION (changes whenever the canonical config changes).

export const PLANS_VERSION = "${version}";

export const PLANS = ${json} as const;
`;

try {
  writeFileSync(outPath, file, "utf8");
  console.log(`gen-plans: wrote ${outPath} (PLANS_VERSION=${version})`);
  console.log(
    `gen-plans: charged figures = ${payload.plans
      .map((p) => `${p.id} ₹${p.monthlyInclGst}`)
      .join(", ")} incl. GST`
  );
} catch (err) {
  console.error(
    "gen-plans: failed to write ../frontend/src/lib/plans.autogen.ts — run from the server/ directory."
  );
  throw err;
}
